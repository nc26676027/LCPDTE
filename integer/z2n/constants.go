package z2n

// FixedPointConstant is an exact signed magnitude divided by 2^FractionBits.
// Strings are retained verbatim so the port can be compared without decimal
// conversion against Gao--Zheng's z-constants.h.
type FixedPointConstant struct {
	Magnitude    string
	Negative     bool
	FractionBits uint
}

// RootConstant is one complex root from the published upper-half-plane table.
type RootConstant struct {
	Real FixedPointConstant
	Imag FixedPointConstant
}

func root(realMagnitude string, realNegative bool, imagMagnitude string, imagNegative bool) RootConstant {
	return RootConstant{
		Real: FixedPointConstant{Magnitude: realMagnitude, Negative: realNegative, FractionBits: rootFractionBits},
		Imag: FixedPointConstant{Magnitude: imagMagnitude, Negative: imagNegative, FractionBits: rootFractionBits},
	}
}

